import fs from "node:fs";
import path from "node:path";
import { errorEntries } from "../src/data/errors.js";
import { reviewedSources } from "../src/data/reviewedSources.js";
import { entrySearchText } from "../src/search.js";

const outputDir = path.resolve("src/data/generated");
const productsDir = path.join(outputDir, "products");
const searchStopWords = new Set(
  "the and for from with this that into when where your you are was were has have had but can may its then than after before because while through using use used source linked reports".split(" "),
);

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function moduleSource(name, value) {
  return `// Generated by tools/generate-published-catalog.mjs. Do not edit directly.\nexport const ${name} = ${JSON.stringify(value, null, 2)};\n`;
}

function searchEntry(entry) {
  const searchText = [
    ...new Set(
      entrySearchText(entry)
        .toLowerCase()
        .match(/[a-z0-9]+/g)
        ?.filter((token) => (token.length >= 2 || /^\d+$/.test(token)) && !searchStopWords.has(token)) ?? [],
    ),
  ].join(" ");
  return {
    id: entry.id,
    code: entry.code,
    message: entry.message,
    product: entry.product,
    versions: entry.versions,
    confidence: entry.confidence,
    reviewedDate: entry.reviewedDate,
    summary: entry.summary,
    fixStatus: entry.fixStatus,
    validationStatus: entry.validationStatus,
    scenarioCount: entry.scenarios?.length ?? 0,
    sources: entry.sources.map(({ sourceType, title, url }) => ({ sourceType, title, url })),
    searchText,
  };
}

fs.mkdirSync(productsDir, { recursive: true });
for (const file of fs.readdirSync(productsDir).filter((name) => name.endsWith(".js"))) {
  fs.unlinkSync(path.join(productsDir, file));
}

const entriesByProduct = Map.groupBy(errorEntries, (entry) => entry.product);
const manifestLines = [
  "// Generated by tools/generate-published-catalog.mjs. Do not edit directly.",
  "export const productLoaders = {",
];

for (const [product, entries] of [...entriesByProduct].sort(([a], [b]) => a.localeCompare(b))) {
  const slug = slugify(product);
  fs.writeFileSync(path.join(productsDir, `${slug}.js`), moduleSource("productEntries", entries));
  manifestLines.push(`  ${JSON.stringify(product)}: () => import(${JSON.stringify(`./products/${slug}.js`)}),`);
}

manifestLines.push("};", "");
fs.writeFileSync(path.join(outputDir, "catalogManifest.js"), manifestLines.join("\n"));
fs.writeFileSync(path.join(outputDir, "catalogIndex.js"), moduleSource("catalogIndex", errorEntries.map(searchEntry)));
fs.writeFileSync(path.join(outputDir, "reviewedSources.js"), moduleSource("reviewedSources", reviewedSources));

console.log(
  `Generated ${errorEntries.length} index rows, ${entriesByProduct.size} product modules, and ${reviewedSources.length} reviewed sources.`,
);
