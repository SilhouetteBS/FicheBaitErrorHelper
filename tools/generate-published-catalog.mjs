import fs from "node:fs";
import path from "node:path";
import { setTimeout as delay } from "node:timers/promises";
import { errorEntries } from "../src/data/errors.js";
import { reviewedSources } from "../src/data/reviewedSources.js";
import { entrySearchText } from "../src/search.js";

const dataDir = path.resolve("src/data");
const outputDir = path.join(dataDir, "generated");
const lockPath = path.join(dataDir, ".catalog-generation.lock");
const searchStopWords = new Set(
  "the and for from with this that into when where your you are was were has have had but can may its then than after before because while through using use used source linked reports".split(" "),
);

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function moduleSource(name, value) {
  return `// Generated by tools/generate-published-catalog.mjs. Do not edit directly.\nexport const ${name} = ${JSON.stringify(value, null, 2)};\n`;
}

const reviewStatusByUrl = new Map(reviewedSources.filter((item) => item.url).map((item) => [item.url, item.reviewStatus]));

function searchEntry(entry) {
  const searchText = [
    ...new Set(
      entrySearchText(entry)
        .toLowerCase()
        .match(/[a-z0-9]+/g)
        ?.filter((token) => (token.length >= 2 || /^\d+$/.test(token)) && !searchStopWords.has(token)) ?? [],
    ),
  ].join(" ");
  const sourceTypes = [...new Set(entry.sources.map((source) => source.sourceType))];
  const reviewStatuses = [...new Set(entry.sources.map((source) => reviewStatusByUrl.get(source.url) ?? "curated"))];
  return {
    id: entry.id,
    ...(entry.aliases?.length ? { aliases: entry.aliases } : {}),
    code: entry.code,
    message: entry.message,
    product: entry.product,
    versions: entry.versions,
    confidence: entry.confidence,
    reviewedDate: entry.reviewedDate,
    fixStatus: entry.fixStatus,
    validationStatus: entry.validationStatus,
    scenarioCount: entry.scenarios?.length ?? 0,
    sources: sourceTypes.map((sourceType) => ({ sourceType })),
    reviewStatuses,
    searchText,
  };
}

async function acquireLock() {
  for (let attempt = 0; attempt < 200; attempt += 1) {
    try {
      return fs.openSync(lockPath, "wx");
    } catch (error) {
      if (error.code !== "EEXIST") throw error;
      await delay(50);
    }
  }
  throw new Error(`Timed out waiting for catalog generation lock: ${lockPath}`);
}

const lockHandle = await acquireLock();
const temporaryDir = path.join(dataDir, `.generated-${process.pid}-${Date.now()}`);

try {
  const productsDir = path.join(temporaryDir, "products");
  fs.mkdirSync(productsDir, { recursive: true });

  const entriesByProduct = Map.groupBy(errorEntries, (entry) => entry.product);
  const manifestLines = [
    "// Generated by tools/generate-published-catalog.mjs. Do not edit directly.",
    "export const productLoaders = {",
  ];

  for (const [product, entries] of [...entriesByProduct].sort(([a], [b]) => a.localeCompare(b))) {
    const slug = slugify(product);
    fs.writeFileSync(path.join(productsDir, `${slug}.js`), moduleSource("productEntries", entries));
    manifestLines.push(`  ${JSON.stringify(product)}: () => import(${JSON.stringify(`./products/${slug}.js`)}),`);
  }

  const reviewedDates = reviewedSources.map((item) => item.reviewedDate).filter(Boolean).sort();
  const catalogStats = {
    entryCount: errorEntries.length,
    reviewedSourceCount: reviewedSources.length,
    latestSourceDate: reviewedDates.at(-1) ?? null,
    sourceTypes: [...new Set(reviewedSources.map((item) => item.sourceType))],
  };

  manifestLines.push("};", "");
  fs.writeFileSync(path.join(temporaryDir, "catalogManifest.js"), manifestLines.join("\n"));
  fs.writeFileSync(path.join(temporaryDir, "catalogIndex.js"), moduleSource("catalogIndex", errorEntries.map(searchEntry)));
  fs.writeFileSync(path.join(temporaryDir, "catalogStats.js"), moduleSource("catalogStats", catalogStats));
  fs.writeFileSync(path.join(temporaryDir, "reviewedSources.js"), moduleSource("reviewedSources", reviewedSources));

  fs.rmSync(outputDir, { recursive: true, force: true });
  fs.renameSync(temporaryDir, outputDir);
  console.log(
    `Generated ${errorEntries.length} index rows, ${entriesByProduct.size} product modules, and ${reviewedSources.length} reviewed sources.`,
  );
} finally {
  fs.rmSync(temporaryDir, { recursive: true, force: true });
  fs.closeSync(lockHandle);
  fs.rmSync(lockPath, { force: true });
}
